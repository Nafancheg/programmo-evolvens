// Optional development-tool check. Replays recorded data, never executes genomes.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {frame} = require('../programmo_evolvens/lab_ui/development_view.js');
const evidence = JSON.parse(fs.readFileSync(path.join(__dirname, '../world/wsl2/evidence/development-2026-11-01.json'), 'utf8'));
const events = evidence.events, original = JSON.stringify(events);
const first = frame(events, 0);
assert.equal(first.cells.length, 1);
assert.equal(first.cells[0].mechanisms.length, 0);
assert.equal(first.links.length, 0);
assert.equal(first.value, null);
const created = frame(events, events.findIndex(event => event.event === 'cell_created'));
assert.equal(created.cells.length, 2);
assert.equal(created.links.length, 0);
assert.equal(created.value, null);
const linked = frame(events, events.findIndex(event => event.event === 'link_created'));
assert.equal(linked.links.length, 1);
assert.equal(linked.value, null);
const final = frame(events, events.length - 1), result = evidence.run.result.development;
assert.equal(final.value, 'hello');
assert.equal(final.cells[0].used_steps, result.cells[0].used_steps);
assert.equal(final.cells[1].used_steps, result.cells[1].used_steps);
assert.deepEqual(final.cells[1].memory, result.cells[1].memory);
assert.equal(final.firedRules.length, 4);
assert.equal(frame(events, -1).cursor, 0);
assert.equal(frame(events, 1000).cursor, events.length - 1);
assert.equal(JSON.stringify(events), original);
console.log('Recorded development frames: initial, cell creation, connection, output and immutability verified.');
